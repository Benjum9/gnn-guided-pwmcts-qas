def rollout(node: Node, steps: int, simulation_strategy) -> Node:
    new_node = node
    for _ in range(steps):
        if simulation_strategy and any(simulation_strategy.values()):
            if random.uniform(0, 1) >= 0.1:
                last_qubit_modified = new_node.state.circuit.data[-1][1].index
                new_node = new_node.simulation(simulation_strategy, qubit=last_qubit_modified)
            else:
                new_node = new_node.define_children(
                    prob_choice={"a": 100, "d": 0, "s": 0, "c": 0, "p": 0},
                    roll_out=True,
                    stop_deterministic=False,
                )
        else:
            new_node = new_node.define_children(
                prob_choice={"a": 100, "d": 0, "s": 0, "c": 0, "p": 0},
                roll_out=True,
                stop_deterministic=False,
            )
    return new_node


def evaluate(node: Node, evaluation_function) -> float:
    return node.state.evaluation(evaluation_function)


def backpropagate(node: Node, result: float) -> None:
    while node is not None:
        node.visits += 1
        node.value += result
        node = node.parent


def commit(current_node: Node, criteria: str) -> Node:
    return current_node.best_child(criteria=criteria)


def extract_best_path(root: Node, criteria: str) -> Tuple[List[QuantumCircuit], List[int], List[int], List[float], Node]:
    node = root
    qc_path: List[QuantumCircuit] = []
    children_counts: List[int] = []
    visits: List[int] = []
    values: List[float] = []

    while True:
        qc_path.append(node.state.circuit)
        children_counts.append(len(node.children))
        visits.append(node.visits)
        values.append(node.value)

        if node.isTerminal or len(node.children) == 0:
            break
        node = node.best_child(criteria=criteria)

    return qc_path, children_counts, visits, values, node


# ============================================================
# Main configurable MCTS
# ============================================================
def mcts(
    root: Node,
    budget: int,
    evaluation_function=None,
    criteria: str = "average_value",
    rollout_type: str = "classic",
    roll_out_steps: int = 0,
    simulation: bool = False,
    branches=False,
    choices: dict = None,
    epsilon: Optional[float] = None,
    stop_deterministic: bool = False,
    ucb_value: float = 0.4,
    pw_C: float = 1.0,
    pw_alpha: float = 0.3,
    verbose: bool = False,

    # evaluation mode
    evaluation_mode: str = "oracle",         # "oracle" | "gnn"
    gnn_value_function: Optional[Callable[[QuantumCircuit], float]] = None,

    # expansion mode
    expansion_mode: str = "random",          # "random" | "gnn_guided"
    gnn_rank_function: Optional[Callable[[List[QuantumCircuit]], np.ndarray]] = None,
    gnn_candidate_pool_size: int = 8,
    ignore_stop_in_guided: bool = True,

    # selection control
    prefer_unvisited_by_prior: bool = True,  # kept for compatibility
    use_prior_in_ucb: bool = False,
    prior_ucb_weight: float = 0.0,

    # coupling-map plumbing (optional override if root was created without one)
    coupling_map: Optional[Iterable[Tuple[int, int]]] = None,
    directed_coupling: bool = True,
) -> Dict[str, Any]:
    """
    Configurable backend-basis MCTS with:

    Expansion options:
      - expansion_mode="random"
      - expansion_mode="gnn_guided"

    Evaluation options:
      - evaluation_mode="oracle" : uses evaluation_function
      - evaluation_mode="gnn"    : uses gnn_value_function as ONLY evaluator

    Optional prior term in visited-child selection:
      score = Q + U + w * p / n_i
    where:
      - w = prior_ucb_weight
      - p = child.prior_value
      - n_i = child.visits

    If use_prior_in_ucb=False, behavior is exactly the same as before.
    """

    if choices is None:
        choices = {'a': 50, 'd': 10, 's': 20, 'c': 20, 'p': 0}

    if evaluation_mode not in {"oracle", "gnn"}:
        raise ValueError("evaluation_mode must be 'oracle' or 'gnn'.")

    if expansion_mode not in {"random", "gnn_guided"}:
        raise ValueError("expansion_mode must be 'random' or 'gnn_guided'.")

    if evaluation_mode == "oracle" and evaluation_function is None:
        raise ValueError("evaluation_mode='oracle' requires evaluation_function.")
    if evaluation_mode == "gnn" and gnn_value_function is None:
        raise ValueError("evaluation_mode='gnn' requires gnn_value_function.")
    if expansion_mode == "gnn_guided" and gnn_rank_function is None:
        raise ValueError("expansion_mode='gnn_guided' requires gnn_rank_function.")

    if coupling_map is not None:
        root.coupling_map = normalize_coupling_map(coupling_map, directed_coupling)
        root.directed_coupling = bool(directed_coupling)

    prob_choice = {'a': 100, 'd': 0, 's': 0, 'c': 0}
    original_root = root

    if verbose:
        print("Root Node:\n", root)

    oracle_eval_calls = 0
    gnn_eval_calls = 0
    gnn_rank_batches = 0
    gnn_rank_candidates_scored = 0

    def evaluate_node(node: Node) -> float:
        nonlocal oracle_eval_calls, gnn_eval_calls

        if evaluation_mode == "oracle":
            oracle_eval_calls += 1
            return float(evaluation_function(node.state.circuit))

        if node.prior_value is not None:
            return float(node.prior_value)

        gnn_eval_calls += 1
        val = float(gnn_value_function(node.state.circuit))
        node.prior_value = val
        return val

    best_overall_value = evaluate_node(root)
    best_overall_qc = root.state.circuit.copy()
    root.visits = max(root.visits, 1)

    n_qubits = len(root.state.circuit.qubits)

    if simulation:
        qubit_ngrams_counter = {q: Counter() for q in range(n_qubits)}
        quality_results_by_qubit = defaultdict(lambda: defaultdict(list))
        n = 2
    else:
        qubit_ngrams_counter, quality_results_by_qubit = None, None
        n = None

    for epoch_counter in range(budget):
        current_node = root

        if current_node.visits > budget / 20 and len(current_node.children) > 2:
            if epsilon is not None:
                if random.uniform(0, 1) >= epsilon:
                    root = commit(current_node, criteria)
            else:
                root = commit(current_node, criteria)

            if verbose:
                print("Committed to", root)
            current_node = root

        while (
            not current_node.isTerminal
            and current_node.is_fully_expanded(branches=branches, pw_C=pw_C, pw_alpha=pw_alpha)
        ):
            current_node = select(
                current_node,
                exploration=ucb_value,
                use_prior_in_ucb=use_prior_in_ucb,
                prior_ucb_weight=prior_ucb_weight,
            )
            if verbose:
                print("Selection:", current_node)

        if not current_node.isTerminal:
            if expansion_mode == "random":
                current_node = expand_random(
                    current_node,
                    prob_choice=prob_choice,
                    stop_deterministic=stop_deterministic,
                )
            else:
                current_node, n_added, n_ranked = expand_gnn_guided_bulk(
                    current_node,
                    prob_choice=prob_choice,
                    branches=branches,
                    pw_C=pw_C,
                    pw_alpha=pw_alpha,
                    gnn_rank_function=gnn_rank_function,
                    gnn_candidate_pool_size=gnn_candidate_pool_size,
                    ignore_stop_in_guided=ignore_stop_in_guided,
                )
                gnn_rank_batches += 1
                gnn_rank_candidates_scored += int(n_ranked)

            if verbose:
                print("Expanded / chosen node:\n", current_node)

        if not current_node.isTerminal:
            if isinstance(roll_out_steps, int):
                leaf_node = rollout(current_node, steps=roll_out_steps, simulation_strategy=quality_results_by_qubit)
                result = evaluate_node(leaf_node)

                if result > best_overall_value:
                    best_overall_value = result
                    best_overall_qc = leaf_node.state.circuit.copy()

                if roll_out_steps > 1 and rollout_type != "classic":
                    node_to_evaluate = leaf_node
                    result_list = [result]
                    for _ in range(roll_out_steps):
                        if node_to_evaluate.parent is None:
                            break
                        result_list.append(evaluate_node(node_to_evaluate.parent))
                        node_to_evaluate = node_to_evaluate.parent

                    if rollout_type == "max":
                        result = max(result_list)
                    elif rollout_type == "mean":
                        result = sum(result_list) / len(result_list)
                    else:
                        raise NotImplementedError(f"Rollout type '{rollout_type}' is not implemented.")
            else:
                raise TypeError("roll_out_steps must be an integer")
        else:
            result = evaluate_node(current_node)
            if result > best_overall_value:
                best_overall_value = result
                best_overall_qc = current_node.state.circuit.copy()

        if verbose:
            print("Reward:", result)

        backpropagate(current_node, result)

        if simulation:
            qubit_ngrams_counter = update_ngrams(current_node.state.circuit, n, qubit_ngrams_counter)
            quality_results_by_qubit = update_conditional_results(
                qubit_ngrams_counter, quality_results_by_qubit, result
            )

        if current_node.tree_depth == 2 * n_qubits:
            prob_choice = choices

    qc_path, children_counts, visits, values, final_node = extract_best_path(original_root, criteria)

    return {
        "qc": qc_path,
        "children": children_counts,
        "visits": visits,
        "value": values,
        "final_path_qc": final_node.state.circuit,
        "best_overall_qc": best_overall_qc,
        "best_overall_value": best_overall_value,
        "evaluation_mode": evaluation_mode,
        "expansion_mode": expansion_mode,
        "oracle_eval_calls": oracle_eval_calls,
        "gnn_eval_calls": gnn_eval_calls,
        "gnn_rank_batches": gnn_rank_batches,
        "gnn_rank_candidates_scored": gnn_rank_candidates_scored,
        "use_prior_in_ucb": use_prior_in_ucb,
        "prior_ucb_weight": prior_ucb_weight,
    }
