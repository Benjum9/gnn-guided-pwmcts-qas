# Convert quantum circuit to string using qasm2 (normally)
def circuit_to_key(qc: QuantumCircuit) -> str:
    if qasm2 is not None:
        return qasm2.dumps(qc)
    if hasattr(qc, "qasm"):
        print("used qasm instead of qasm2, old quiskit version")
        return qc.qasm()
    print("no qasm available")
    return str(qc)


# Use normalize_coupling_map from structure.Gateset
def normalize_coupling_map(
    coupling_map: Optional[Iterable[Tuple[int, int]]],
    directed_coupling: bool,
) -> Set[Tuple[int, int]]:
    return GateSet._normalize_coupling_map(coupling_map, directed_coupling)


# return the max number of children a node is allowed to expand
# Use boolean branches = false to use progressive widening
def pw_max_children(node: "Node", branches, pw_C: float, pw_alpha: float) -> int:
    if isinstance(branches, bool):
        if branches:
            raise NotImplementedError("Double progressive widening is not implemented yet.")
        t = max(int(node.visits), 1)
        return max(1, int(np.ceil(pw_C * (t ** pw_alpha))))
    elif isinstance(branches, int):
        return int(branches)
    else:
        raise TypeError("The 'branches' parameter must be an int or bool.")


# return how many more children the node is allowed to expand
# (according to progressive widening if branches = false)
def pw_available_slots(node: "Node", branches, pw_C: float, pw_alpha: float) -> int:
    k = pw_max_children(node, branches, pw_C, pw_alpha)
    return max(0, k - len(node.children))


class Node:
    def __init__(
            self,
            state: Circuit,
            max_depth: int,
            parent=None,
            coupling_map: Optional[Iterable[Tuple[int, int]]] = None,
            directed_coupling: bool = True,
    ):
        self.state = state
        self.isTerminal = False
        self.parent = parent
        self.children: List["Node"] = []
        self.visits = 0
        self.value = 0.0
        self.max_depth = max_depth
        self.tree_depth = 0 if parent is None else parent.tree_depth + 1

        # Backend basis gate set
        self.gate_set = "backend"

        self.stop_is_done = False
        self.action = None
        self.counter_cx = self.state.circuit.count_ops().get("cx", 0)

        # Coupling map support
        self.directed_coupling = bool(directed_coupling)
        if parent is not None:
            self.coupling_map: Set[Tuple[int, int]] = set(parent.coupling_map)
            self.directed_coupling = bool(parent.directed_coupling)
        else:
            self.coupling_map = normalize_coupling_map(coupling_map, self.directed_coupling)

        # Optional GNN prior information
        self.prior_value: Optional[float] = None

    def __repr__(self):
        return (
            f"Tree depth: {self.tree_depth}  -  Generated by Action: {self.action}  -  "
            f"Number of Children: {len(self.children)}  -  Visits: {self.visits}  -  "
            f"Value: {self.value}   -  "
            f"CouplingEdges: {len(self.coupling_map)}  -  "
            f"Quantum Circuit (CNOT counts)= {self.counter_cx}):\n{self.state.circuit}"
        )

    def _make_gateset(self) -> GateSet:
        return GateSet(
            self.gate_set,
            coupling_map=self.coupling_map,
            directed_coupling=self.directed_coupling,
        )

    def is_fully_expanded(self, branches, pw_C, pw_alpha):
        return pw_available_slots(self, branches, pw_C, pw_alpha) == 0

    def define_children(self, prob_choice, stop_deterministic, roll_out: bool = False):
        parent = self
        qc = parent.state.circuit.copy()
        stop = self.stop_is_done if not roll_out else True
        gate_set = parent._make_gateset()

        def det_stop():
            new_qc, action = parent.state.get_legal_action(
                gate_set, self.max_depth, prob_choice, stop
            )
            new_qc = new_qc(qc)

            if new_qc is None:
                temporary_prob_choice = {"a": 50, "s": 50, "c": 0, "d": 0}
                new_qc, action = parent.state.get_legal_action(
                    gate_set, self.max_depth, temporary_prob_choice, stop
                )
                new_qc = new_qc(qc)

            new_node = node_from_qc(new_qc, parent_node=self, roll_out=roll_out)
            new_node.action = action
            self.counter_cx = self.state.circuit.count_ops().get("cx", 0)
            return new_node

        def prob_stop():
            new_qc, action = parent.state.get_legal_action(
                gate_set, self.max_depth, prob_choice, stop
            )
            new_qc = new_qc(qc)

            if new_qc == "stop":
                self.isTerminal = True
                self.stop_is_done = True
                self.counter_cx = self.state.circuit.count_ops().get("cx", 0)
                return self

            if new_qc is None:
                temporary_prob_choice = {"a": 50, "s": 50, "c": 0, "d": 0}
                new_qc, action = parent.state.get_legal_action(
                    gate_set, self.max_depth, temporary_prob_choice, stop
                )
                new_qc = new_qc(qc)

                if new_qc is None:
                    temporary_prob_choice = {"a": 100, "s": 0, "c": 0, "d": 0}
                    new_qc, action = parent.state.get_legal_action(
                        gate_set, self.max_depth, temporary_prob_choice, stop
                    )
                    new_qc = new_qc(qc)

            if isinstance(new_qc, QuantumCircuit):
                new_state = Circuit(new_qc.num_qubits, new_qc.num_clbits).building_state(new_qc)
                new_node = Node(
                    new_state,
                    max_depth=self.max_depth,
                    parent=self,
                    coupling_map=self.coupling_map,
                    directed_coupling=self.directed_coupling,
                )
                new_node.action = action
                self.counter_cx = self.state.circuit.count_ops().get("cx", 0)
                if not roll_out:
                    self.children.append(new_node)
                return new_node

            raise TypeError(
                f"Expected QuantumCircuit, got {type(new_qc)} "
                f"(action={action}, value_repr={repr(new_qc)[:200]})"
            )

        return det_stop() if stop_deterministic else prob_stop()

    def best_child(self, criteria: str):
        children_with_values = [(child, child.value, child.visits) for child in self.children]
        if criteria == "value":
            return max(children_with_values, key=lambda x: x[1])[0]
        if criteria == "average_value":
            return max(children_with_values, key=lambda x: x[1] / max(x[2], 1))[0]
        if criteria == "visits":
            return max(children_with_values, key=lambda x: x[2])[0]
        raise ValueError("criteria must be one of: visits, value, average_value")

    # Not revised, no simulation in the thesis
    def simulation(self, simulation_strategy, qubit: int):
        """
        Simulates most likely gates for a qubit based on n-gram conditional probabilities.

        In backend mode, CX must respect the coupling map.
        """
        qc = self.state.circuit.copy()

        ngrams_quality = simulation_strategy[qubit]
        last_gate = qc.data[-1][0].name if qc.data else None

        gates_ngram, quality_ngram = [], []
        for ngram, quality_scores in ngrams_quality.items():
            if isinstance(ngram, tuple) and last_gate in ngram[-1]:
                gates_ngram.append(ngram[0])
                quality_ngram.append(quality_scores[0])

        quality_ngram = [-q if q < 0 else 0 for q in quality_ngram]
        if len(quality_ngram) > 0:
            norm = np.linalg.norm(quality_ngram)
            if norm > 0:
                quality_ngram = quality_ngram / norm

        if gates_ngram and sum(quality_ngram) > 0:
            next_gate = random.choices(gates_ngram, weights=quality_ngram, k=1)[0]
            gate_set = self._make_gateset()

            if next_gate == "rz":
                qc.rz(random.uniform(0, 2 * np.pi), qubit)
            elif next_gate == "sx":
                qc.sx(qubit)
            elif next_gate == "x":
                qc.x(qubit)
            elif next_gate == "cx":
                legal_edges = gate_set.legal_cx_edges(qc.num_qubits)
                edge_candidates = [e for e in legal_edges if qubit in e]
                if edge_candidates:
                    edge = random.choice(edge_candidates)
                    qc.cx(edge[0], edge[1])

        new_state = Circuit(qc.num_qubits, qc.num_clbits).building_state(qc)
        return Node(
            new_state,
            max_depth=self.max_depth,
            parent=self,
            coupling_map=self.coupling_map,
            directed_coupling=self.directed_coupling,
        )


def make_root_node_from_qc(
        quantum_circuit: QuantumCircuit,
        max_depth: int,
        coupling_map: Optional[Iterable[Tuple[int, int]]] = None,
        directed_coupling: bool = True,
) -> Node:
    new_state = Circuit(quantum_circuit.num_qubits, quantum_circuit.num_clbits).building_state(quantum_circuit)
    return Node(
        new_state,
        max_depth=max_depth,
        parent=None,
        coupling_map=coupling_map,
        directed_coupling=directed_coupling,
    )


def node_from_qc(quantum_circuit: QuantumCircuit, parent_node: Node, roll_out: bool) -> Node:
    if not isinstance(quantum_circuit, QuantumCircuit):
        raise TypeError("quantum_circuit must be a QuantumCircuit")
    new_state = Circuit(quantum_circuit.num_qubits, quantum_circuit.num_clbits).building_state(quantum_circuit)
    new_child = Node(
        new_state,
        max_depth=parent_node.max_depth,
        parent=parent_node,
        coupling_map=parent_node.coupling_map,
        directed_coupling=parent_node.directed_coupling,
    )
    if not roll_out:
        parent_node.children.append(new_child)
    return new_child


def sample_virtual_candidate(parent: Node, prob_choice: Dict[str, int]) -> Dict[str, Any]:
    """
    Sample ONE candidate expansion from `parent` WITHOUT appending it to the tree.
    This mirrors Node.define_children(..., stop_deterministic=False).
    """
    qc = parent.state.circuit.copy()
    stop = parent.stop_is_done
    gate_set = parent._make_gateset()

    def sample_once(local_prob_choice: Dict[str, int]) -> Tuple[Any, Any]:
        new_qc_fn, action = parent.state.get_legal_action(
            gate_set, parent.max_depth, local_prob_choice, stop
        )
        return new_qc_fn(qc), action

    new_qc, action = sample_once(prob_choice)

    if new_qc == "stop":
        return {
            "kind": "stop",
            "qc": parent.state.circuit.copy(),
            "action": action,
        }

    if new_qc is None:
        temporary_prob_choice = {"a": 50, "s": 50, "c": 0, "d": 0}
        new_qc, action = sample_once(temporary_prob_choice)

        if new_qc is None:
            temporary_prob_choice = {"a": 100, "s": 0, "c": 0, "d": 0}
            new_qc, action = sample_once(temporary_prob_choice)

    if isinstance(new_qc, QuantumCircuit):
        return {
            "kind": "child",
            "qc": new_qc,
            "action": action,
        }

    raise TypeError(
        f"Expected QuantumCircuit or 'stop', got {type(new_qc)} "
        f"(action={action}, value_repr={repr(new_qc)[:200]})"
    )


def materialize_virtual_candidate(
        parent: Node,
        candidate: Dict[str, Any],
        *,
        prior_value: Optional[float] = None,
) -> Node:
    kind = candidate["kind"]

    if kind == "stop":
        parent.isTerminal = True
        parent.stop_is_done = True
        parent.counter_cx = parent.state.circuit.count_ops().get("cx", 0)
        return parent

    if kind == "child":
        child = node_from_qc(candidate["qc"], parent_node=parent, roll_out=False)
        child.action = candidate.get("action")
        child.prior_value = prior_value
        parent.counter_cx = parent.state.circuit.count_ops().get("cx", 0)
        return child

    raise ValueError(f"Unknown candidate kind: {kind}")


# ============================================================
# Selection: Use UCB1
# ============================================================

def select(
    node: Node,
    exploration: float = 0.4,
    use_prior_in_ucb: bool = False,
    prior_ucb_weight: float = 0.0,
) -> Node:
    """
    Selection rule:
    - If every child has visits > 1: use UCB, optionally with an extra prior term
      score = Q + U + w * p / n_i
    - Otherwise: choose among unvisited children (visits == 0)
      the one with the highest prior_value
    """

    if len(node.children) == 0:
        raise ValueError("select() called on a node with no children")

    if all(child.visits >= 1 for child in node.children):
        log_visits = np.log(max(node.visits, 1))

        best_child = None
        best_score = -float("inf")

        for child in node.children:
            q_term = child.value / child.visits
            u_term = exploration * np.sqrt(log_visits / child.visits)

            p_term = 0.0
            if use_prior_in_ucb and child.prior_value is not None:
                p_term = prior_ucb_weight * child.prior_value / child.visits # pw/ni
                #p_term = prior_ucb_weight * child.prior_value   # pw

            score = q_term + u_term + p_term

            if score > best_score:
                best_score = score
                best_child = child

        return best_child

    # Otherwise, pick an unvisited child with highest prior_value
    unvisited = [child for child in node.children if child.visits == 0]
    if unvisited:
        with_prior = [child for child in unvisited if child.prior_value is not None]
        if with_prior:
            return max(with_prior, key=lambda c: c.prior_value)

        print("no prior, problem")
        return random.choice(unvisited)

    raise RuntimeError("Selection reached an unexpected state.")


