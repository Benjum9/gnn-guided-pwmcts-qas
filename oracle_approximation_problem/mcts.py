# EXPANSION: Random expansion and GNN-guided expansion
# ============================================================

def expand_random(node: Node, prob_choice: dict, stop_deterministic: bool) -> Node:
    new_node = node.define_children(prob_choice=prob_choice, stop_deterministic=stop_deterministic)
    if stop_deterministic:
        stop_node = node_from_qc(new_node.state.circuit, new_node, roll_out=False)
        stop_node.isTerminal = True
        return stop_node
    return new_node


def expand_gnn_guided_bulk(
    node: Node,
    *,
    prob_choice: Dict[str, int],
    branches,
    pw_C: float,
    pw_alpha: float,
    gnn_rank_function: Callable[[List[QuantumCircuit]], np.ndarray],
    gnn_candidate_pool_size: int,
    ignore_stop_in_guided: bool = True,
) -> Tuple[Node, int, int]:
    """
    Fill ALL currently available PW slots with the top GNN-ranked children.

    Assumption:
        gnn_rank_function returns fidelity directly, so HIGHER is better.

    Returns:
        chosen_child_for_current_iteration,
        n_children_added,
        n_candidates_ranked
    """
    slots_to_fill = pw_available_slots(node, branches, pw_C, pw_alpha)
    if slots_to_fill <= 0:
        return node, 0, 0

    pool_size = max(int(gnn_candidate_pool_size), int(slots_to_fill))

    existing_keys = {circuit_to_key(child.state.circuit) for child in node.children}
    virtual_candidates: List[Dict[str, Any]] = []
    qc_candidates: List[QuantumCircuit] = []

    attempts = 0
    max_attempts = max(pool_size * 8, pool_size + 16)

    while len(virtual_candidates) < pool_size and attempts < max_attempts:
        attempts += 1
        cand = sample_virtual_candidate(node, prob_choice)

        if cand["kind"] == "stop":
            if ignore_stop_in_guided:
                continue
            continue

        key = circuit_to_key(cand["qc"])
        if key in existing_keys:
            continue

        existing_keys.add(key)
        virtual_candidates.append(cand)
        qc_candidates.append(cand["qc"])

    if not virtual_candidates:
        child = expand_random(node, prob_choice=prob_choice, stop_deterministic=False)
        return child, 1, 1

    scores = np.asarray(gnn_rank_function(qc_candidates), dtype=float).reshape(-1)
    if scores.shape[0] != len(virtual_candidates):
        raise ValueError(
            f"gnn_rank_function returned {scores.shape[0]} scores for {len(virtual_candidates)} candidates."
        )

    order = np.argsort(-scores)

    added_children: List[Node] = []
    for idx in order[:slots_to_fill]:
        cand = virtual_candidates[int(idx)]
        prior_value = float(scores[int(idx)])
        child = materialize_virtual_candidate(
            node,
            cand,
            prior_value=prior_value,
        )
        added_children.append(child)

    if not added_children:
        child = expand_random(node, prob_choice=prob_choice, stop_deterministic=False)
        return child, 1, len(virtual_candidates)

    return added_children[0], len(added_children), len(virtual_candidates)


